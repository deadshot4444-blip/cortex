const anatObject = value => value && typeof value === 'object' && !Array.isArray(value);
function validAnatRun(run) {
  if (
    !anatObject(run) ||
    !VIEWS[run.view] ||
    !['find', 'name'].includes(run.mode) ||
    !Array.isArray(run.queue) ||
    !run.queue.length ||
    new Set(run.queue).size !== run.queue.length ||
    !run.queue.every(id => VIEW_BONES[run.view].includes(id)) ||
    !anatObject(run.metadata) ||
    !run.queue.every(id => anatObject(run.metadata[id]) && typeof run.metadata[id].name === 'string') ||
    !Array.isArray(run.answers) ||
    run.answers.length > run.queue.length ||
    !Array.isArray(run.orders) ||
    !Number.isInteger(run.idx) ||
    run.idx < 0 ||
    run.idx > run.queue.length ||
    run.idx > run.answers.length ||
    run.answers.length > run.idx + 1 ||
    (run.done && !run.completedAt) ||
    (run.completedAt && run.answers.length !== run.queue.length) ||
    !Number.isFinite(run.startedAt) ||
    (run.completedAt != null && !Number.isFinite(run.completedAt))
  )
    return false;
  return (
    run.answers.every(
      (answer, index) =>
        answer &&
        answer.target === run.queue[index] &&
        VIEW_BONES[run.view].includes(answer.selected) &&
        typeof answer.correct === 'boolean' &&
        answer.correct === (answer.selected === answer.target) &&
        Number.isFinite(answer.at)
    ) &&
    run.orders.every(
      (order, index) =>
        Array.isArray(order) &&
        new Set(order).size === order.length &&
        order.includes(run.queue[index]) &&
        order.every(id => run.queue.includes(id))
    )
  );
}
