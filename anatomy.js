/* ---------- render: a region game ---------- */

function startAnat(view, mode, restart = false) {
  if (StudyStorage.paused || !VIEWS[view] || !['explore', 'find', 'name'].includes(mode)) return;
  anatSystem = Object.keys(SYSTEMS).find(system => SYSTEMS[system].regions.includes(view)) || anatSystem;
  const bones = VIEW_BONES[view].filter(id => BONE_META[id]);
  if (mode === 'explore') anat = { view, mode, queue: [], idx: 0, correct: 0, done: false };
  else {
    const key = `${view}:${mode}`,
      prior = ANAT_RUNS.sessions[key];
    if (prior && !restart) anat = prior;
    else {
      if (prior) ANAT_RUNS.history = [...ANAT_RUNS.history, prior].slice(-50);
      anat = {
        view,
        mode,
        queue: shuffle(bones),
        idx: 0,
        correct: 0,
        done: false,
        answers: [],
        orders: [],
        startedAt: Date.now(),
        metadata: Object.fromEntries(bones.map(id => [id, { ...BONE_META[id] }])),
      };
      ANAT_RUNS.sessions[key] = anat;
      if (!saveAnatRun()) return;
    }
    anat.correct = anat.answers.filter(answer => answer.correct).length;
  }
  anatUrl(view, mode);
  renderAnatView();
}

